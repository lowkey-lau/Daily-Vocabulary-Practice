import fs from 'node:fs/promises';
import { pinyin } from 'pinyin-pro';

const SELECTED_PATH = 'content/selected-words.json';
const SOURCE_PATH = 'content/source/hsk-2.0-level1-2.json';
const OUTPUT_TS = 'miniprogram/data/words.ts';
const OUTPUT_JSON = 'content/core-40.json';

// pinyin-pro 对少数轻声词会给全声调，这里人工校正。
const PINYIN_OVERRIDES = {
  学生: 'xué sheng',
  朋友: 'péng you',
};

const UPCOMING_BOOKS = [
  {
    id: 'dialect-family',
    title: '方言 · 家庭称呼',
    subtitle: '爸爸妈妈、公公婆婆',
    tag: '筹备中',
  },
  {
    id: 'dialect-food',
    title: '方言 · 日常饮食',
    subtitle: '买菜、做饭、吃饭',
    tag: '筹备中',
  },
  {
    id: 'dialect-weather',
    title: '方言 · 天气与出行',
    subtitle: '下雨、好热、坐地铁',
    tag: '筹备中',
  },
];

async function main() {
  const selected = JSON.parse(await fs.readFile(SELECTED_PATH, 'utf8'));
  const source = JSON.parse(await fs.readFile(SOURCE_PATH, 'utf8'));
  const byTerm = new Map(source.words.map((word) => [word.term, word]));

  if (!Array.isArray(selected.words) || !selected.words.length) {
    throw new Error('content/selected-words.json 里没有 words');
  }

  const missing = selected.words.filter((word) => !byTerm.has(word.term));
  if (missing.length) {
    console.error(
      `以下词不在 HSK 1–2 源词表中：${missing.map((w) => w.term).join('、')}`
    );
    process.exit(1);
  }

  const words = selected.words.map((word, index) => {
    const sourceWord = byTerm.get(word.term);
    const reading =
      PINYIN_OVERRIDES[word.term] ||
      pinyin(word.term, { toneType: 'symbol' });
    return {
      id: `hsk-${String(index + 1).padStart(3, '0')}`,
      term: word.term,
      reading,
      meaning: word.meaning,
      pos: word.pos,
      example: word.example,
      exampleMeaning: word.exampleMeaning,
      tags: word.tags,
    };
  });

  const book = {
    id: 'hsk-daily-test',
    title: '普通话 · 日常词（HSK 1–2 选词）',
    subtitle: `${words.length} 个日常词，先跑通录音`,
    description:
      '词目和拼音参考 HSK 1–2 词表；释义、例句为原创。长辈可以按自家口音录，子孙听录音选释义；正式版再按方言 / 语言词书接入。',
    level: '入门',
    total: words.length,
  };

  const typeBlock = `export type Word = {
  id: string;
  term: string;
  reading: string;
  meaning: string;
  pos: string;
  example: string;
  exampleMeaning: string;
  tags: string[];
};

`;

  const generated = `// AUTO-GENERATED by scripts/build-words.mjs
// 请编辑 content/selected-words.json，然后运行 npm run build:words。
// 词目 / 等级 / 词频来自 HSK 1–2 源词表；释义与例句为本项目原创。

${typeBlock}export const WORDS: Word[] = ${JSON.stringify(words, null, 2)};

export const BOOK = ${JSON.stringify(book, null, 2)};

export const UPCOMING_BOOKS = ${JSON.stringify(UPCOMING_BOOKS, null, 2)};
`;

  const review = {
    source: source.source,
    pinyin: {
      generator: 'pinyin-pro',
      license: 'MIT',
      overrides: PINYIN_OVERRIDES,
    },
    wordCount: words.length,
    words: words.map((word) => {
      const sourceWord = byTerm.get(word.term);
      return {
        ...word,
        hskLevel: sourceWord.hskLevel,
        frequency: sourceWord.frequency,
      };
    }),
  };

  await fs.writeFile(OUTPUT_TS, generated);
  await fs.writeFile(OUTPUT_JSON, `${JSON.stringify(review, null, 2)}\n`);

  console.log(`Generated ${OUTPUT_TS} (${words.length} words)`);
  console.log(`Generated ${OUTPUT_JSON}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
