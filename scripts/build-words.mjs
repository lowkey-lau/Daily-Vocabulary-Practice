import fs from 'node:fs/promises';
import { pinyin } from 'pinyin-pro';

const SELECTED_PATH = 'content/selected-words.json';
const SOURCE_PATH = 'content/source/hsk-2.0-level1-2.json';
const OUTPUT_TS = 'miniprogram/data/words.ts';
const OUTPUT_JSON = 'content/core.json';

const STAGE_LABELS = {
  family: '第一阶段 · 家人称呼',
  daily: '第二阶段 · 日常场景',
  basic: '第三阶段 · 基础词汇',
};

// pinyin-pro 对少数轻声词会给全声调，这里人工校正。
const PINYIN_OVERRIDES = {
  学生: 'xué sheng',
};

const UPCOMING_BOOKS = [
  {
    id: 'dialect-family',
    title: '方言 · 家庭称呼',
    subtitle: '爸爸妈妈、公公婆婆',
    tag: '筹备中',
  },
  {
    id: 'dialect-food',
    title: '方言 · 日常饮食',
    subtitle: '买菜、做饭、吃饭',
    tag: '筹备中',
  },
  {
    id: 'dialect-weather',
    title: '方言 · 天气与出行',
    subtitle: '下雨、好热、坐地铁',
    tag: '筹备中',
  },
];

async function main() {
  const selected = JSON.parse(await fs.readFile(SELECTED_PATH, 'utf8'));
  const source = JSON.parse(await fs.readFile(SOURCE_PATH, 'utf8'));
  const byTerm = new Map(source.words.map((word) => [word.term, word]));

  if (!Array.isArray(selected.words) || !selected.words.length) {
    throw new Error('content/selected-words.json 里没有 words');
  }

  const supplemental = selected.words
    .filter((word) => !byTerm.has(word.term))
    .map((word) => word.term);

  const words = selected.words.map((word, index) => {
    const sourceWord = byTerm.get(word.term);
    const stageLabel = STAGE_LABELS[word.stage];
    if (!stageLabel) {
      throw new Error(`未知阶段：${word.term} → ${word.stage}`);
    }
    const reading =
      PINYIN_OVERRIDES[word.term] ||
      pinyin(word.term, { toneType: 'symbol' });
    return {
      id: `field-${String(index + 1).padStart(3, '0')}`,
      term: word.term,
      reading,
      meaning: word.meaning,
      pos: word.pos,
      example: word.example,
      exampleMeaning: word.exampleMeaning,
      tags: word.tags,
      stage: word.stage,
      stageLabel,
    };
  });

  const book = {
    id: 'field-family-daily-test',
    title: '家人与日常 · 口音测试',
    subtitle: `先家人称呼，再日常场景 · ${words.length} 词`,
    description:
      '40 个词分三组：第一阶段家人称呼 → 第二阶段日常场景 → 第三阶段基础词汇。长辈按自家口音录，子孙听录音选释义；正式版再按方言 / 语言词书接入。',
    level: '入门',
    total: words.length,
  };

  const typeBlock = `export type Word = {
  id: string;
  term: string;
  reading: string;
  meaning: string;
  pos: string;
  example: string;
  exampleMeaning: string;
  tags: string[];
  stage: 'family' | 'daily' | 'basic';
  stageLabel: string;
};

`;

  const generated = `// AUTO-GENERATED by scripts/build-words.mjs
// 请编辑 content/selected-words.json，然后运行 npm run build:words。
// 词目 / 等级 / 词频来自 HSK 1–2 源词表；释义与例句为本项目原创。

${typeBlock}export const WORDS: Word[] = ${JSON.stringify(words, null, 2)};

export const BOOK = ${JSON.stringify(book, null, 2)};

export const UPCOMING_BOOKS = ${JSON.stringify(UPCOMING_BOOKS, null, 2)};
`;

  const review = {
    source: source.source,
    pinyin: {
      generator: 'pinyin-pro',
      license: 'MIT',
      overrides: PINYIN_OVERRIDES,
    },
    wordCount: words.length,
    words: words.map((word) => {
      const sourceWord = byTerm.get(word.term);
      return {
        ...word,
        origin: sourceWord ? 'hsk' : 'supplemental',
        hskLevel: sourceWord ? sourceWord.hskLevel : null,
        frequency: sourceWord ? sourceWord.frequency : null,
      };
    }),
  };

  await fs.writeFile(OUTPUT_TS, generated);
  await fs.writeFile(OUTPUT_JSON, `${JSON.stringify(review, null, 2)}\n`);

  const hskCount = words.filter((word) => byTerm.has(word.term)).length;
  console.log(
    `Generated ${OUTPUT_TS} (${words.length} words: ${hskCount} HSK, ${
      words.length - hskCount
    } supplemental)`
  );
  console.log(`Generated ${OUTPUT_JSON}`);
  if (supplemental.length) {
    console.log(`补充词：${supplemental.join('、')}`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
